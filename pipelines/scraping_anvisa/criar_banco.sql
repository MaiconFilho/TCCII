CREATE TABLE public.bulas (
    nome_normalizado TEXT NOT NULL,
    nome_anvisa TEXT,
    numero_registro TEXT,
    expediente TEXT,
    principios_ativos TEXT,
    composicao TEXT,
    status TEXT NOT NULL,
    tentativas INTEGER DEFAULT 0,
    tempo_total_segundos NUMERIC,
    CONSTRAINT pk_bulas PRIMARY KEY (nome_normalizado)
);

CREATE TABLE public.bulas_interacoes (
    nome_normalizado TEXT NOT NULL,
    trecho_interacoes TEXT,
    status_extracao TEXT,
    detalhe_revisao TEXT,
    tempo_leitura_segundos NUMERIC,
    tempo_inferencia_segundos NUMERIC,
    tempo_total_segundos NUMERIC,
    CONSTRAINT pk_bulas_interacoes PRIMARY KEY (nome_normalizado),
    CONSTRAINT fk_bulas_interacoes_nome_normalizado FOREIGN KEY (nome_normalizado) REFERENCES public.bulas (nome_normalizado) ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE public.processamentos_interacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    medicamento_origem TEXT NOT NULL,
    status TEXT NOT NULL,
    versao_processamento TEXT NOT NULL,
    modelo TEXT NOT NULL,
    quantidade_janelas INTEGER,
    janelas_concluidas INTEGER,
    quantidade_relacoes INTEGER,
    quantidade_rejeicoes INTEGER,
    chamadas_llm INTEGER,
    tempo_inferencia_segundos NUMERIC,
    tempo_total_segundos NUMERIC,
    pico_memoria_mb NUMERIC,
    concluido_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    invalidado_em TIMESTAMPTZ,
    resumo_geral TEXT,
    resumo_geral_simples TEXT,
    resumo_status TEXT,
    resumo_modelo TEXT,
    resumo_erro TEXT,
    resumo_gerado_em TIMESTAMPTZ,
    reescrita_controle JSONB DEFAULT '{}'::jsonb,
    resumo_tempo_inferencia_segundos FLOAT8,
    resumo_tempo_total_segundos FLOAT8,
    CONSTRAINT pk_processamentos_interacoes PRIMARY KEY (id),
    CONSTRAINT fk_processamentos_interacoes_medicamento_origem FOREIGN KEY (medicamento_origem) REFERENCES public.bulas (nome_normalizado) ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE public.interacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    medicamento_origem TEXT NOT NULL,
    processamento_id BIGINT NOT NULL,
    alvo TEXT NOT NULL,
    tipo_alvo TEXT NOT NULL,
    resumo TEXT NOT NULL,
    evidencia TEXT NOT NULL,
    resumo_card TEXT,
    resumo_card_simples TEXT,
    resumo_status TEXT,
    resumo_modelo TEXT,
    resumo_origem TEXT,
    resumo_tempo_segundos FLOAT8,
    resumo_erro TEXT,
    resumo_atualizado_em TIMESTAMPTZ,
    reescrita_controle JSONB DEFAULT '{}'::jsonb,
    CONSTRAINT pk_interacoes PRIMARY KEY (id),
    CONSTRAINT fk_interacoes_medicamento_origem FOREIGN KEY (medicamento_origem) REFERENCES public.bulas (nome_normalizado) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_interacoes_processamento_id FOREIGN KEY (processamento_id) REFERENCES public.processamentos_interacoes (id) ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE public.interacoes_medicamentos (
    interacao_id BIGINT NOT NULL,
    medicamento_relacionado TEXT NOT NULL,
    criterio_vinculo TEXT,
    invalidado_em TIMESTAMPTZ,
    CONSTRAINT pk_interacoes_medicamentos PRIMARY KEY (interacao_id, medicamento_relacionado),
    CONSTRAINT fk_interacoes_medicamentos_interacao_id FOREIGN KEY (interacao_id) REFERENCES public.interacoes (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_interacoes_medicamentos_medicamento_relacionado FOREIGN KEY (medicamento_relacionado) REFERENCES public.bulas (nome_normalizado) ON UPDATE RESTRICT ON DELETE RESTRICT
);



