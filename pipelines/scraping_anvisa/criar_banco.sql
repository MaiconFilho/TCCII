CREATE OR REPLACE VIEW public.processamentos_interacoes_vigentes WITH (security_invoker=true) AS
SELECT DISTINCT ON (p.medicamento_origem) p.id, p.medicamento_origem, p.status,
    p.versao_processamento, p.modelo, p.quantidade_janelas, p.janelas_concluidas,
    p.quantidade_relacoes, p.quantidade_rejeicoes, p.chamadas_llm,
    p.tempo_inferencia_segundos, p.tempo_total_segundos, p.pico_memoria_mb,
    p.concluido_em, p.invalidado_em, p.resumo_geral, p.resumo_geral_simples,
    p.resumo_status, p.resumo_modelo, p.resumo_erro, p.resumo_gerado_em,
    p.reescrita_controle, p.resumo_tempo_inferencia_segundos, p.resumo_tempo_total_segundos
FROM public.processamentos_interacoes p
JOIN public.bulas_interacoes bi ON bi.nome_normalizado=p.medicamento_origem
WHERE p.invalidado_em IS NULL
  AND p.status IN ('CONCLUIDO_COM_RELACOES','CONCLUIDO_SEM_RELACOES')
  AND bi.status_extracao='CONCLUIDO' AND NULLIF(BTRIM(bi.trecho_interacoes),'') IS NOT NULL
ORDER BY p.medicamento_origem, p.id DESC;

CREATE OR REPLACE VIEW public.processamentos_interacoes_registrados WITH (security_invoker=true) AS
SELECT DISTINCT ON (p.medicamento_origem) p.id, p.medicamento_origem, p.status,
    p.versao_processamento, p.modelo, p.quantidade_janelas, p.janelas_concluidas,
    p.quantidade_relacoes, p.quantidade_rejeicoes, p.chamadas_llm,
    p.tempo_inferencia_segundos, p.tempo_total_segundos, p.pico_memoria_mb,
    p.concluido_em, p.invalidado_em, p.resumo_geral, p.resumo_geral_simples,
    p.resumo_status, p.resumo_modelo, p.resumo_erro, p.resumo_gerado_em,
    p.reescrita_controle, p.resumo_tempo_inferencia_segundos, p.resumo_tempo_total_segundos
FROM public.processamentos_interacoes p
JOIN public.bulas_interacoes bi ON bi.nome_normalizado=p.medicamento_origem
WHERE p.invalidado_em IS NULL
  AND p.status IN ('CONCLUIDO_COM_RELACOES','CONCLUIDO_SEM_RELACOES','REVISAO_NECESSARIA')
  AND bi.status_extracao='CONCLUIDO' AND NULLIF(BTRIM(bi.trecho_interacoes),'') IS NOT NULL
ORDER BY p.medicamento_origem, p.id DESC;

COMMENT ON VIEW public.processamentos_interacoes_vigentes IS
    'Modelo60/v1: última conclusão não invalidada da base fixa. Falha/revisão posterior não retira conclusão válida.';
COMMENT ON VIEW public.processamentos_interacoes_registrados IS
    'Modelo60/v1: último resultado concluído ou em revisão, para retomada; não publica revisão.';

-- Validação sem criar uma sétima FK. O lock do pai serializa com sua alteração.
CREATE OR REPLACE FUNCTION public.interamed_validar_origem() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$
DECLARE origem text;
BEGIN
    IF TG_TABLE_NAME='interacoes' THEN
        SELECT medicamento_origem INTO origem FROM public.processamentos_interacoes
        WHERE id=NEW.processamento_id FOR SHARE;
        IF origem IS DISTINCT FROM NEW.medicamento_origem THEN
            RAISE EXCEPTION 'Origem da interação diverge do processamento' USING ERRCODE='23514';
        END IF;
    ELSIF NEW.medicamento_origem IS DISTINCT FROM OLD.medicamento_origem THEN
        RAISE EXCEPTION 'Origem do processamento é imutável; retire e registre outro processamento' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.interamed_validar_origem() FROM PUBLIC;
DROP TRIGGER IF EXISTS interamed_origem_interacao ON public.interacoes;
CREATE TRIGGER interamed_origem_interacao BEFORE INSERT OR UPDATE OF medicamento_origem,processamento_id
ON public.interacoes FOR EACH ROW EXECUTE FUNCTION public.interamed_validar_origem();
DROP TRIGGER IF EXISTS interamed_origem_processamento ON public.processamentos_interacoes;
CREATE TRIGGER interamed_origem_processamento BEFORE UPDATE OF medicamento_origem
ON public.processamentos_interacoes FOR EACH ROW EXECUTE FUNCTION public.interamed_validar_origem();

-- Controles antigos ficam byte a byte equivalentes na migração. Alterações
-- posteriores nas entradas invalidam a publicação; nova publicação limpa a marca.
CREATE OR REPLACE FUNCTION public.interamed_invalidar_reescrita() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$
DECLARE pid bigint;
BEGIN
    IF TG_TABLE_NAME='interacoes' THEN
        IF TG_OP='UPDATE' AND ROW(OLD.alvo,OLD.tipo_alvo,OLD.resumo_card,OLD.evidencia,OLD.processamento_id,OLD.medicamento_origem)
            IS NOT DISTINCT FROM ROW(NEW.alvo,NEW.tipo_alvo,NEW.resumo_card,NEW.evidencia,NEW.processamento_id,NEW.medicamento_origem) THEN RETURN NEW; END IF;
        FOR pid IN SELECT DISTINCT x FROM unnest(ARRAY[
            CASE WHEN TG_OP<>'INSERT' THEN OLD.processamento_id END,
            CASE WHEN TG_OP<>'DELETE' THEN NEW.processamento_id END]) x WHERE x IS NOT NULL LOOP
            UPDATE public.interacoes SET reescrita_controle=COALESCE(reescrita_controle,'{}'::jsonb)||'{"entrada_invalidada":true}'::jsonb
            WHERE processamento_id=pid AND resumo_card_simples IS NOT NULL
                AND ((TG_OP<>'INSERT' AND alvo=OLD.alvo AND tipo_alvo=OLD.tipo_alvo)
                  OR (TG_OP<>'DELETE' AND alvo=NEW.alvo AND tipo_alvo=NEW.tipo_alvo))
                AND NOT (TG_OP='UPDATE' AND id=NEW.id
                    AND NEW.reescrita_controle->'publicado' IS DISTINCT FROM OLD.reescrita_controle->'publicado'
                    AND NEW.reescrita_controle->'publicado'->>'prompt'='linguagem-simples/37');
            UPDATE public.processamentos_interacoes SET reescrita_controle=COALESCE(reescrita_controle,'{}'::jsonb)||'{"entrada_invalidada":true}'::jsonb
            WHERE id=pid AND resumo_geral_simples IS NOT NULL;
        END LOOP;
    ELSIF TG_TABLE_NAME='bulas' THEN
        IF NEW.principios_ativos IS NOT DISTINCT FROM OLD.principios_ativos THEN RETURN NEW; END IF;
        UPDATE public.interacoes SET reescrita_controle=COALESCE(reescrita_controle,'{}'::jsonb)||'{"entrada_invalidada":true}'::jsonb
        WHERE medicamento_origem=NEW.nome_normalizado AND resumo_card_simples IS NOT NULL;
        UPDATE public.processamentos_interacoes SET reescrita_controle=COALESCE(reescrita_controle,'{}'::jsonb)||'{"entrada_invalidada":true}'::jsonb
        WHERE medicamento_origem=NEW.nome_normalizado AND resumo_geral_simples IS NOT NULL;
    ELSE
        IF NEW.resumo_geral IS NOT DISTINCT FROM OLD.resumo_geral
            OR (NEW.reescrita_controle->'publicado' IS DISTINCT FROM OLD.reescrita_controle->'publicado'
                AND NEW.reescrita_controle->'publicado'->>'prompt'='linguagem-simples/37') THEN RETURN NEW; END IF;
        UPDATE public.processamentos_interacoes SET reescrita_controle=COALESCE(reescrita_controle,'{}'::jsonb)||'{"entrada_invalidada":true}'::jsonb
        WHERE id=NEW.id AND resumo_geral_simples IS NOT NULL;
    END IF;
    RETURN NULL;
END $$;
REVOKE ALL ON FUNCTION public.interamed_invalidar_reescrita() FROM PUBLIC;
DROP TRIGGER IF EXISTS interamed_entrada_card ON public.interacoes;
CREATE TRIGGER interamed_entrada_card AFTER INSERT OR DELETE OR UPDATE OF alvo,tipo_alvo,resumo_card,evidencia,processamento_id,medicamento_origem
ON public.interacoes FOR EACH ROW EXECUTE FUNCTION public.interamed_invalidar_reescrita();
DROP TRIGGER IF EXISTS interamed_entrada_geral ON public.processamentos_interacoes;
CREATE TRIGGER interamed_entrada_geral AFTER UPDATE OF resumo_geral
ON public.processamentos_interacoes FOR EACH ROW EXECUTE FUNCTION public.interamed_invalidar_reescrita();
DROP TRIGGER IF EXISTS interamed_entrada_cadastro ON public.bulas;
CREATE TRIGGER interamed_entrada_cadastro AFTER UPDATE OF principios_ativos
ON public.bulas FOR EACH ROW EXECUTE FUNCTION public.interamed_invalidar_reescrita();

-- Fonte fixa: uma correção excepcional exige retirada explícita dos resultados.
CREATE OR REPLACE FUNCTION public.interamed_proteger_fonte() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$
BEGIN
    IF TG_TABLE_NAME='bulas_interacoes' THEN
        IF ROW(NEW.nome_normalizado,NEW.trecho_interacoes,NEW.status_extracao) IS NOT DISTINCT FROM ROW(OLD.nome_normalizado,OLD.trecho_interacoes,OLD.status_extracao) THEN RETURN NEW; END IF;
    ELSE
        IF ROW(NEW.numero_registro,NEW.expediente) IS NOT DISTINCT FROM ROW(OLD.numero_registro,OLD.expediente) THEN RETURN NEW; END IF;
    END IF;
    IF EXISTS (SELECT 1 FROM public.processamentos_interacoes WHERE medicamento_origem IN (OLD.nome_normalizado,NEW.nome_normalizado)
        AND invalidado_em IS NULL AND status IN ('CONCLUIDO_COM_RELACOES','CONCLUIDO_SEM_RELACOES','REVISAO_NECESSARIA')) THEN
        RAISE EXCEPTION 'Base fixa: invalide explicitamente os processamentos antes de corrigir a fonte' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.interamed_proteger_fonte() FROM PUBLIC;
DROP TRIGGER IF EXISTS interamed_fonte_extraida ON public.bulas_interacoes;
CREATE TRIGGER interamed_fonte_extraida BEFORE UPDATE OF nome_normalizado,trecho_interacoes,status_extracao ON public.bulas_interacoes
FOR EACH ROW EXECUTE FUNCTION public.interamed_proteger_fonte();
DROP TRIGGER IF EXISTS interamed_fonte_bula ON public.bulas;
CREATE TRIGGER interamed_fonte_bula BEFORE UPDATE OF numero_registro,expediente ON public.bulas
FOR EACH ROW EXECUTE FUNCTION public.interamed_proteger_fonte();

